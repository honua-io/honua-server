/// <summary>
/// Single field or attachment control definition in a package.
/// </summary>
public sealed class FormFieldDefinition
{
    /// <summary>Stable field identifier used by clients and submissions.</summary>
    [JsonPropertyName("fieldId")]
    public string? FieldId { get; init; }

    /// <summary>Human-readable field label.</summary>
    [JsonPropertyName("label")]
    public string? Label { get; init; }

    /// <summary>Optional help text.</summary>
    [JsonPropertyName("hint")]
    public string? Hint { get; init; }

    /// <summary>Form field type such as text, number, date, choice, geometry, or attachment.</summary>
    [JsonPropertyName("type")]
    public string? Type { get; init; }

    /// <summary>Target layer attribute field. Attachment fields do not require a target field.</summary>
    [JsonPropertyName("targetField")]
    public string? TargetField { get; init; }

    /// <summary>Optional section id containing this field.</summary>
    [JsonPropertyName("sectionId")]
    public string? SectionId { get; init; }

    /// <summary>Whether a submission must provide a value for this field.</summary>
    [JsonPropertyName("required")]
    public bool Required { get; init; }

    /// <summary>Whether clients should render the control read-only.</summary>
    [JsonPropertyName("readOnly")]
    public bool ReadOnly { get; init; }

    /// <summary>Whether the field carries sensitive values that should be minimized in records.</summary>
    [JsonPropertyName("private")]
    public bool Private { get; init; }

    /// <summary>Optional default value encoded as JSON.</summary>
    [JsonPropertyName("defaultValue")]
    public JsonElement? DefaultValue { get; init; }

    /// <summary>Domain or coded-value choice policy for this field.</summary>
    [JsonPropertyName("domain")]
    public FormFieldDomainDefinition? Domain { get; init; }

    /// <summary>Declarative validation rules applied by the server.</summary>
    [JsonPropertyName("validation")]
    public FormValidationRule[] Validation { get; init; } = [];

    /// <summary>Conditional visibility policy for this field.</summary>
    [JsonPropertyName("visibility")]
    public FormConditionalRule? Visibility { get; init; }
}

