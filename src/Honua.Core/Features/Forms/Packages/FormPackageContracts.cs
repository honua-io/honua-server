using System.Text.Json;
using System.Text.Json.Serialization;

namespace Honua.Core.Features.Forms.Packages;

/// <summary>
/// Stable lifecycle states for server-owned form packages.
/// </summary>
public static class FormPackageStatus
{
    /// <summary>Editable package draft.</summary>
    public const string Draft = "draft";

    /// <summary>Immutable package version available for runtime submission.</summary>
    public const string Published = "published";

    /// <summary>Retained package version that should not be selected as current.</summary>
    public const string Archived = "archived";
}

/// <summary>
/// Feature edit operations that a published form package may permit.
/// </summary>
public static class FormSubmissionOperations
{
    /// <summary>Create a new feature.</summary>
    public const string Create = "create";

    /// <summary>Update an existing feature.</summary>
    public const string Update = "update";

    /// <summary>Delete an existing feature.</summary>
    public const string Delete = "delete";
}

/// <summary>
/// Survey-style form package document governed by Honua Server.
/// </summary>
public sealed class FormPackageDocument
{
    /// <summary>Wire schema version for this package document.</summary>
    [JsonPropertyName("schemaVersion")]
    public string SchemaVersion { get; init; } = "honua.form-package.v1";

    /// <summary>Stable package identifier. Generated by the server when omitted on create.</summary>
    [JsonPropertyName("formId")]
    public string? FormId { get; init; }

    /// <summary>Human-readable title shown in builder and field clients.</summary>
    [JsonPropertyName("title")]
    public string? Title { get; init; }

    /// <summary>Optional package description.</summary>
    [JsonPropertyName("description")]
    public string? Description { get; init; }

    /// <summary>Target feature service and layer for submissions.</summary>
    [JsonPropertyName("target")]
    public FormTargetDefinition? Target { get; init; }

    /// <summary>Ordered sections or groups in the form.</summary>
    [JsonPropertyName("sections")]
    public FormSectionDefinition[] Sections { get; init; } = [];

    /// <summary>Field definitions, including target-field bindings.</summary>
    [JsonPropertyName("fields")]
    public FormFieldDefinition[] Fields { get; init; } = [];

    /// <summary>Runtime edit policy for accepted submissions.</summary>
    [JsonPropertyName("submitPolicy")]
    public FormSubmitPolicy SubmitPolicy { get; init; } = new();

    /// <summary>Package-level and per-field attachment policy.</summary>
    [JsonPropertyName("attachmentPolicy")]
    public FormAttachmentPolicy AttachmentPolicy { get; init; } = new();

    /// <summary>Privacy policy applied while validating, storing, and auditing submissions.</summary>
    [JsonPropertyName("privacyPolicy")]
    public FormPrivacyPolicy PrivacyPolicy { get; init; } = new();

    /// <summary>Offline and sync policy advertised to field clients.</summary>
    [JsonPropertyName("offlinePolicy")]
    public FormOfflinePolicy OfflinePolicy { get; init; } = new();

    /// <summary>Optional provenance describing how the package was authored.</summary>
    [JsonPropertyName("provenance")]
    public FormProvenanceRef? Provenance { get; init; }

    /// <summary>Opaque package metadata. Values must be policy-safe and non-secret.</summary>
    [JsonPropertyName("metadata")]
    public Dictionary<string, string>? Metadata { get; init; }
}

