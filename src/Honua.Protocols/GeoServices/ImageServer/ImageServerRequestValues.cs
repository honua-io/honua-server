using Microsoft.Extensions.Primitives;

namespace Honua.Protocols.GeoServices.ImageServer;

internal static class ImageServerRequestValues
{
    internal static string? GetString(IReadOnlyDictionary<string, StringValues> values, string key)
        => values.TryGetValue(key, out var raw) ? raw.ToString() : null;
}
