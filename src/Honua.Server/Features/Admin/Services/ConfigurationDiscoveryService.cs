public sealed class ConfigurationDiscoveryService
{
    private readonly IServiceProvider _serviceProvider;
    private readonly IConfigurationDiscovery _configurationDiscovery;
    private readonly IConfiguration _configuration;
    private readonly IWebHostEnvironment _environment;
    private readonly ILogger<ConfigurationDiscoveryService> _logger;
    private readonly ConfigurationDocumentationService _documentationService;

    public ConfigurationDiscoveryService(
        IServiceProvider serviceProvider,
        IConfigurationValidator configurationValidator,
        IConfiguration configuration,
        IWebHostEnvironment environment,
        ILogger<ConfigurationDiscoveryService> logger,
        ConfigurationDocumentationService documentationService)
    {
        _serviceProvider = serviceProvider;
        _configurationDiscovery = configurationValidator as IConfigurationDiscovery
            ?? throw new InvalidOperationException("Configuration validator does not provide configuration discovery metadata.");
        _configuration = configuration;
        _environment = environment;
        _logger = logger;
        _documentationService = documentationService;
    }

    public async Task<ConfigurationDiscoveryResult> DiscoverConfigurationAsync(CancellationToken cancellationToken = default)
    {
        var stopwatch = System.Diagnostics.Stopwatch.StartNew();

        try
        {
            // Get existing documentation
            var documentation = _documentationService.BuildDocumentation();

            // Discover all IOptions types
            var optionsTypes = await DiscoverOptionsTypesAsync(cancellationToken);

            // Extract metadata for each type
            var metadata = await ExtractMetadataAsync(optionsTypes, cancellationToken);

            // Generate auto-documentation for undocumented types
            var autoGenerated = GenerateAutoDocumentation(optionsTypes, metadata);

            // Validate secret references
            var secretValidation = await ValidateSecretReferencesAsync(cancellationToken);

            // Get configuration audit information
            var auditInfo = GetConfigurationAuditInfo();

            ConfigurationDiscoveryLog.DiscoveryCompleted(_logger, optionsTypes.Count, metadata.Count, stopwatch.ElapsedMilliseconds);

            return new ConfigurationDiscoveryResult
            {
                ExistingDocumentation = documentation,
                DiscoveredTypes = optionsTypes,
                ExtractedMetadata = metadata,
                AutoGeneratedDocumentation = autoGenerated,
                SecretValidation = secretValidation,
                AuditInformation = auditInfo,
                DiscoveryDurationMs = stopwatch.ElapsedMilliseconds,
                Timestamp = DateTimeOffset.UtcNow
            };
        }
        catch (Exception ex)
        {
            ConfigurationDiscoveryLog.DiscoveryFailed(_logger, ex.Message, ex);
            throw;
        }
    }

    private async Task<List<ConfigurationTypeInfo>> DiscoverOptionsTypesAsync(CancellationToken cancellationToken)
    {
        var registeredOptions = _configurationDiscovery.GetAllOptions()
            .DistinctBy(metadata => metadata.OptionsType)
            .ToArray();

        var discoveredTypes = new List<ConfigurationTypeInfo>(registeredOptions.Length);
        foreach (var metadata in registeredOptions)
        {
            cancellationToken.ThrowIfCancellationRequested();
            discoveredTypes.Add(await CreateTypeInfoAsync(metadata));
        }

        return discoveredTypes;
    }

    private async Task<ConfigurationTypeInfo> CreateTypeInfoAsync(ConfigurationOptionsMetadata metadata)
    {
        var optionsType = metadata.OptionsType;
        var currentValues = await GetCurrentConfigurationValuesAsync(optionsType, metadata.SectionName);

        return new ConfigurationTypeInfo
        {
            Type = optionsType,
            SectionName = metadata.SectionName,
            TypeName = optionsType.Name,
            FullTypeName = optionsType.FullName ?? optionsType.Name,
            Assembly = optionsType.Assembly.GetName().Name ?? "Unknown",
            Properties = MapPropertyMetadata(optionsType, metadata.Properties),
            IsRegisteredInDi = true,
            CurrentValues = currentValues
        };
    }

    private static List<PropertyMetadata> MapPropertyMetadata(
        [DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicProperties)] Type optionsType,
        IReadOnlyList<ConfigurationPropertyMetadata> properties)
    {
        var mappedProperties = new List<PropertyMetadata>(properties.Count);
        foreach (var property in properties)
        {
            var propertyInfo = optionsType.GetProperty(property.Name, BindingFlags.Public | BindingFlags.Instance);
            mappedProperties.Add(new PropertyMetadata
            {
                Name = property.Name,
                Type = property.PropertyType.Name,
                FullType = property.PropertyType.FullName ?? property.PropertyType.Name,
                IsRequired = property.IsRequired,
                DefaultValue = property.DefaultValue,
                Description = property.Description,
                ValidationRules = propertyInfo is not null
                    ? ExtractValidationRules(propertyInfo)
                    : ExtractValidationRules(property.ValidationAttributes),
                IsSecret = propertyInfo is not null
                    ? IsSecretProperty(propertyInfo)
                    : IsSecretPropertyName(property.Name)
            });
        }

        return mappedProperties;
    }

    private static string? GetPropertyDescription(PropertyInfo property)
    {
        var descriptionAttr = property.GetCustomAttribute<DescriptionAttribute>();
        if (descriptionAttr?.Description != null)
        {
            return descriptionAttr.Description;
        }

        // Try to extract from XML doc comments if available
        return ExtractXmlDocComment(property);
    }

    private static string? ExtractXmlDocComment(PropertyInfo property)
    {
        // This is a simplified implementation
        // In a full implementation, you'd parse the XML documentation file
        return null;
    }

    private static List<ValidationRuleInfo> ExtractValidationRules(PropertyInfo property)
    {
        return ExtractValidationRules(property.GetCustomAttributes<ValidationAttribute>());
    }

    private static List<ValidationRuleInfo> ExtractValidationRules(IEnumerable<ValidationAttribute> validationAttributes)
    {
        var rules = new List<ValidationRuleInfo>();

        foreach (var attr in validationAttributes)
        {
            var rule = new ValidationRuleInfo
            {
                AttributeType = attr.GetType().Name,
                ErrorMessage = attr.ErrorMessage,
                IsConfigurationValidation = attr is ConfigurationValidationAttribute
            };

            // Extract specific validation details
            switch (attr)
            {
                case RangeAttribute range:
                    rule.MinValue = range.Minimum;
                    rule.MaxValue = range.Maximum;
                    break;
                case StringLengthAttribute stringLength:
                    rule.MinLength = stringLength.MinimumLength;
                    rule.MaxLength = stringLength.MaximumLength;
                    break;
                case ValidTtlAttribute ttlAttr:
                    rule.MinimumTtl = ttlAttr.MinimumTtl.ToString("c", System.Globalization.CultureInfo.InvariantCulture);
                    rule.MaximumTtl = ttlAttr.MaximumTtl.ToString("c", System.Globalization.CultureInfo.InvariantCulture);
                    rule.RecommendedMinimumInProduction = ttlAttr.RecommendedMinimumInProduction?.ToString("c", System.Globalization.CultureInfo.InvariantCulture);
                    break;
            }

            rules.Add(rule);
        }

        return rules;
    }

    private static bool IsSecretProperty(PropertyInfo property)
    {
        var name = property.Name.ToLowerInvariant();
        return IsSecretPropertyName(name)
            || property.GetCustomAttribute<SecretReferenceAttribute>() != null;
    }

    // The secret flag and value masking share one deny-by-default redactor so they agree on what is sensitive.
    private static bool IsSecretPropertyName(string propertyName)
        => ConfigurationSecretRedactor.IsSensitiveName(propertyName);

    // A credential-shaped value is masked even when its property name looks ordinary.
    private static object? RedactConfigurationValue(PropertyInfo property, object? value)
    {
        if (value is null)
        {
            return null;
        }

        return IsSecretProperty(property)
            ? ConfigurationSecretRedactor.Mask
            : ConfigurationSecretRedactor.Redact(property.Name, value);
    }

    private async Task<Dictionary<string, object?>> GetCurrentConfigurationValuesAsync(
        [DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicProperties | DynamicallyAccessedMemberTypes.PublicParameterlessConstructor)] Type type,
        string sectionName)
    {
        var values = new Dictionary<string, object?>();

        try
        {
            var registration = _serviceProvider
                .GetServices<IConfigurationOptionsRegistration>()
                .FirstOrDefault(candidate => candidate.Metadata.OptionsType == type);

            if (registration?.GetConfiguredOptions(_serviceProvider) is { } instance)
            {
                var readableProperties = type.GetProperties(BindingFlags.Public | BindingFlags.Instance)
                    .Where(prop => prop.CanRead && prop.GetIndexParameters().Length == 0);
                foreach (var prop in readableProperties)
                {
                    try
                    {
                        var value = prop.GetValue(instance);
                        values[prop.Name] = RedactConfigurationValue(prop, value);
                    }
                    // Intentional catch-all: per-property loop over reflected configuration
                    // properties for the admin diagnostics view. One property's getter
                    // throwing must not abort the rest of the properties being read.
                    catch (Exception ex) when (ex is not OutOfMemoryException)
                    {
                        ConfigurationDiscoveryLog.PropertyValueReadFailed(_logger, type.FullName ?? type.Name, prop.Name, ex);
                        values[prop.Name] = null;
                    }
                }
            }
            else
            {
                // Fallback to reading from IConfiguration
                var section = _configuration.GetSection(sectionName);
                var readableProperties = type.GetProperties(BindingFlags.Public | BindingFlags.Instance)
                    .Where(prop => prop.CanRead && prop.GetIndexParameters().Length == 0);
                foreach (var prop in readableProperties)
                {
                    var configValue = section[prop.Name];
                    values[prop.Name] = RedactConfigurationValue(prop, configValue);
                }
            }
        }
        // Intentional catch-all: this is a best-effort configuration-value extraction for
        // the admin discovery/diagnostics surface. A failure here (e.g. DI resolution or
        // configuration binding throwing) must not break the overall discovery listing;
        // log it and return whatever values were already collected.
        catch (Exception ex) when (ex is not OutOfMemoryException)
        {
            ConfigurationDiscoveryLog.ValueExtractionError(_logger, type.FullName ?? type.Name, ex.Message);
        }

        return values;
    }

    private static Task<List<ConfigurationMetadata>> ExtractMetadataAsync(List<ConfigurationTypeInfo> types, CancellationToken cancellationToken)
    {
        var metadata = new List<ConfigurationMetadata>();

        foreach (var typeInfo in types)
        {
            cancellationToken.ThrowIfCancellationRequested();

            var meta = new ConfigurationMetadata
            {
                SectionName = typeInfo.SectionName,
                TypeName = typeInfo.TypeName,
                PropertyCount = typeInfo.Properties.Count,
                SecretPropertyCount = typeInfo.Properties.Count(p => p.IsSecret),
                RequiredPropertyCount = typeInfo.Properties.Count(p => p.IsRequired),
                HasValidation = typeInfo.Properties.Any(p => p.ValidationRules.Count > 0),
                IsRegistered = typeInfo.IsRegisteredInDi,
                LastModified = GetLastModifiedTime(typeInfo.Type)
            };

            metadata.Add(meta);
        }

        return Task.FromResult(metadata);
    }

    private static DateTimeOffset GetLastModifiedTime(Type type)
    {
        try
        {
            var assembly = type.Assembly;
            // Not attacker/user-controlled: assembly.GetName().Name comes from an already-loaded
            // .NET assembly, not external input, so it cannot be a rooted path that would cause
            // Path.Combine to silently discard AppContext.BaseDirectory.
            var assemblyPath = Path.Join(AppContext.BaseDirectory, $"{assembly.GetName().Name}.dll");

            if (File.Exists(assemblyPath))
            {
                return File.GetLastWriteTimeUtc(assemblyPath);
            }

            return Directory.Exists(AppContext.BaseDirectory)
                ? Directory.GetLastWriteTimeUtc(AppContext.BaseDirectory)
                : DateTimeOffset.UtcNow;
        }
        catch (Exception caughtException) when (caughtException is not OutOfMemoryException)
        {
            // Best-effort display timestamp only; the type is still discovered and
            // documented normally, so a file-system lookup failure here is not
            // actionable and doesn't need logging (static helper has no logger).
            return DateTimeOffset.UtcNow;
        }
    }

    private static List<AutoGeneratedDocumentationSection> GenerateAutoDocumentation(List<ConfigurationTypeInfo> types, List<ConfigurationMetadata> metadata)
    {
        return types.Select(typeInfo => new AutoGeneratedDocumentationSection
        {
            SectionName = typeInfo.SectionName,
            TypeName = typeInfo.TypeName,
            Description = $"Auto-generated documentation for {typeInfo.TypeName}",
            Properties = typeInfo.Properties.Select(p => new AutoGeneratedPropertyDoc
            {
                Name = p.Name,
                Type = p.Type,
                Description = p.Description ?? GeneratePropertyDescription(p),
                DefaultValue = p.DefaultValue,
                IsRequired = p.IsRequired,
                IsSecret = p.IsSecret,
                EnvironmentVariable = GetEnvironmentVariableName(typeInfo.SectionName, p.Name),
                ValidationSummary = GetValidationSummary(p.ValidationRules)
            }).ToList()
        }).ToList();
    }

    private static string GeneratePropertyDescription(PropertyMetadata property)
    {
        var name = property.Name;

        // Generate description based on common patterns
        if (name.EndsWith("Enabled", StringComparison.Ordinal))
            return $"Enables or disables {name.Replace("Enabled", "").ToLowerInvariant()}";

        if (name.EndsWith("Timeout", StringComparison.Ordinal))
            return $"Timeout duration for {name.Replace("Timeout", "").ToLowerInvariant()} operations";

        if (name.EndsWith("MaxSize", StringComparison.Ordinal) || name.EndsWith("MaxLength", StringComparison.Ordinal))
            return $"Maximum size limit for {name.Replace("Max", "").Replace("Size", "").Replace("Length", "").ToLowerInvariant()}";

        if (name.Contains("Ttl"))
            return $"Time-to-live duration for {name.Replace("Ttl", "").ToLowerInvariant()}";

        return $"Configuration setting for {name}";
    }

    private static string GetEnvironmentVariableName(string sectionName, string propertyName)
    {
        return $"{sectionName}__{propertyName}".Replace(":", "__");
    }

    private static string GetValidationSummary(List<ValidationRuleInfo> rules)
    {
        if (rules.Count == 0)
            return "No validation rules";

        var summaries = new List<string>();

        foreach (var rule in rules)
        {
            switch (rule.AttributeType)
            {
                case "RequiredAttribute":
                    summaries.Add("Required");
                    break;
                case "RangeAttribute" when rule.MinValue != null && rule.MaxValue != null:
                    summaries.Add($"Range: {rule.MinValue} - {rule.MaxValue}");
                    break;
                case "StringLengthAttribute" when rule.MaxLength.HasValue:
                    summaries.Add($"Max length: {rule.MaxLength}");
                    break;
                case "ValidTtlAttribute":
                    summaries.Add($"TTL: {rule.MinimumTtl} - {rule.MaximumTtl}");
                    break;
            }
        }

        return summaries.Count > 0 ? string.Join(", ", summaries) : "Custom validation";
    }

    private async Task<SecretValidationResult> ValidateSecretReferencesAsync(CancellationToken cancellationToken)
    {
        var result = new SecretValidationResult
        {
            TotalSecrets = 0,
            ValidSecrets = 0,
            InvalidSecrets = 0,
            Issues = new List<SecretValidationIssue>()
        };

        try
        {
            var secretProvider = _serviceProvider.GetService<ISecretProvider>();
            if (secretProvider == null)
            {
                result.Issues.Add(new SecretValidationIssue
                {
                    SecretReference = "N/A",
                    Issue = "ISecretProvider not registered",
                    Severity = "Error"
                });
                return result;
            }

            // Scan configuration for potential secret references
            var secretReferences = ScanForSecretReferences();
            result.TotalSecrets = secretReferences.Count;

            foreach (var secretRef in secretReferences)
            {
                cancellationToken.ThrowIfCancellationRequested();

                try
                {
                    var canResolve = await secretProvider.CanResolveSecretAsync(secretRef, cancellationToken);
                    if (canResolve)
                    {
                        result.ValidSecrets++;
                    }
                    else
                    {
                        result.InvalidSecrets++;
                        result.Issues.Add(new SecretValidationIssue
                        {
                            SecretReference = MaskSecretReference(secretRef),
                            Issue = "Secret reference cannot be resolved",
                            Severity = "Warning"
                        });
                    }
                }
                // Intentional catch-all: per-secret-reference loop; one reference failing to
                // resolve/validate must not abort validation of the remaining references.
                catch (Exception ex) when (ex is not OutOfMemoryException)
                {
                    ConfigurationDiscoveryLog.SecretReferenceValidationFailed(_logger, MaskSecretReference(secretRef), ex);
                    result.InvalidSecrets++;
                    result.Issues.Add(new SecretValidationIssue
                    {
                        SecretReference = MaskSecretReference(secretRef),
                        Issue = "Secret reference validation failed.",
                        Severity = "Error"
                    });
                }
            }
        }
        // Intentional catch-all: this is a best-effort secret-validation summary for the
        // admin diagnostics surface. A failure here (e.g. scanning configuration or resolving
        // the secret provider) must not crash the caller; report it as an issue instead.
        catch (Exception ex) when (ex is not OutOfMemoryException)
        {
            ConfigurationDiscoveryLog.SecretValidationFailed(_logger, ex);
            result.Issues.Add(new SecretValidationIssue
            {
                SecretReference = "N/A",
                Issue = "Secret validation failed.",
                Severity = "Error"
            });
        }

        return result;
    }

    private List<string> ScanForSecretReferences()
    {
        // Scan all configuration sections
        return _configuration.AsEnumerable()
            .Where(section => !string.IsNullOrEmpty(section.Value) && IsLikelySecretReference(section.Value))
            .Select(section => section.Value!)
            .Distinct()
            .ToList();
    }

    private static bool IsLikelySecretReference(string value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return false;

        var colonIndex = value.IndexOf(':', StringComparison.Ordinal);
        if (colonIndex <= 0)
            return false;

        var provider = value[..colonIndex];
        var knownProviders = new[] { "env", "azure", "aws", "vault", "config" };

        return knownProviders.Contains(provider, StringComparer.OrdinalIgnoreCase);
    }

    private static string MaskSecretReference(string secretReference)
    {
        if (string.IsNullOrWhiteSpace(secretReference))
        {
            return "[redacted-secret-reference]";
        }

        var colonIndex = secretReference.IndexOf(':', StringComparison.Ordinal);
        if (colonIndex <= 0)
        {
            return "[redacted-secret-reference]";
        }

        return $"{secretReference[..colonIndex]}:[redacted]";
    }

    private ConfigurationAuditInfo GetConfigurationAuditInfo()
    {
        return new ConfigurationAuditInfo
        {
            Environment = _environment.EnvironmentName,
            MachineName = Environment.MachineName,
            ApplicationName = _environment.ApplicationName,
            ContentRoot = _environment.ContentRootPath,
            ConfigurationSources = _configuration.AsEnumerable()
                .Where(kvp => kvp.Value != null)
                .GroupBy(kvp => GetConfigurationSourceType(kvp.Key))
                .ToDictionary(g => g.Key, g => g.Count()),
            TotalConfigurationKeys = _configuration.AsEnumerable().Count(kvp => kvp.Value != null)
        };
    }

    private static string GetConfigurationSourceType(string key)
    {
        if (key.Contains("__"))
            return "Environment Variables";

        if (key.Contains(':'))
            return "Configuration File";

        return "Other";
    }
}

