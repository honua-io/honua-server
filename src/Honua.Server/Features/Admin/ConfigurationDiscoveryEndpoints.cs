            return ProblemDetailsHelpers.CreateAdminProblem(
                context,
                StatusCodes.Status500InternalServerError,
                "Auto-documentation generation failed");
        }
    }

    private static async Task<IResult> HandleValidateSecretsAsync(
        HttpContext context,
