/// <summary>
/// User behavioral profile for anomaly detection.
/// </summary>
public class UserBehaviorProfile
{
    public string UserId { get; set; } = string.Empty;
    public DateTime FirstSeen { get; set; }
    public DateTime LastSeen { get; set; }
    public List<UserActivity> ActionHistory { get; set; } = new();
    public Dictionary<string, int> ResourceAccessCounts { get; set; } = new();
    public Dictionary<int, int> HourlyActivityCounts { get; set; } = new();
    public Dictionary<DayOfWeek, int> DailyActivityCounts { get; set; } = new();
    public HashSet<string> IpAddresses { get; set; } = new();
    public HashSet<string> UserAgents { get; set; } = new();
    public double AverageSessionDuration { get; set; }
    public int TotalActions { get; set; }

    public void UpdateActivity(AuditEvent auditEvent)
    {
        LastSeen = auditEvent.Timestamp;
        TotalActions++;

        ActionHistory.Add(new UserActivity
        {
            Timestamp = auditEvent.Timestamp,
            EventType = auditEvent.EventType,
            Resource = auditEvent.Resource,
            Action = auditEvent.Action,
            IpAddress = auditEvent.ClientIp,
            UserAgent = auditEvent.UserAgent
        });

        // Maintain sliding window of recent activities
        var cutoff = DateTime.UtcNow.AddDays(-30);
        ActionHistory.RemoveAll(a => a.Timestamp < cutoff);

        // Update resource access counts
        if (!string.IsNullOrEmpty(auditEvent.Resource))
        {
            ResourceAccessCounts[auditEvent.Resource] = ResourceAccessCounts.GetValueOrDefault(auditEvent.Resource, 0) + 1;
        }

        // Update hourly activity
        var hour = auditEvent.Timestamp.Hour;
        HourlyActivityCounts[hour] = HourlyActivityCounts.GetValueOrDefault(hour, 0) + 1;

        // Update daily activity
        var dayOfWeek = auditEvent.Timestamp.DayOfWeek;
        DailyActivityCounts[dayOfWeek] = DailyActivityCounts.GetValueOrDefault(dayOfWeek, 0) + 1;

        // Track IP addresses
        if (!string.IsNullOrEmpty(auditEvent.ClientIp))
        {
            IpAddresses.Add(auditEvent.ClientIp);
        }

        // Track user agents
        if (!string.IsNullOrEmpty(auditEvent.UserAgent))
        {
            UserAgents.Add(auditEvent.UserAgent);
        }
    }

    public HashSet<int> GetTypicalActivityHours()
    {
        var totalActivity = HourlyActivityCounts.Values.Sum();
        var threshold = totalActivity * 0.1; // Hours with at least 10% of activity

        return HourlyActivityCounts
            .Where(kvp => kvp.Value >= threshold)
            .Select(kvp => kvp.Key)
            .ToHashSet();
    }

    public HashSet<string> GetRecentIpAddresses(int days = 7)
    {
        var cutoff = DateTime.UtcNow.AddDays(-days);
        return ActionHistory
            .Where(a => a.Timestamp > cutoff && !string.IsNullOrEmpty(a.IpAddress))
            .Select(a => a.IpAddress!)
            .ToHashSet();
    }

    public int GetRecentActivityCount(TimeSpan timeWindow)
    {
        var cutoff = DateTime.UtcNow.Subtract(timeWindow);
        return ActionHistory.Count(a => a.Timestamp > cutoff);
    }

    public double GetAverageActivityCount()
    {
        if (ActionHistory.Count == 0)
            return 0;

        var days = (DateTime.UtcNow - FirstSeen).TotalDays;
        return days > 0 ? ActionHistory.Count / days : 0;
    }

    public List<UserActivity> GetRecentActions(int count)
    {
        return ActionHistory
            .OrderByDescending(a => a.Timestamp)
            .Take(count)
            .ToList();
    }

    public void CleanupOldData(DateTime cutoff)
    {
        ActionHistory.RemoveAll(a => a.Timestamp < cutoff);

        // Clean up counts for very old data
        if (FirstSeen < cutoff.AddMonths(-6))
        {
            HourlyActivityCounts.Clear();
            DailyActivityCounts.Clear();
            ResourceAccessCounts.Clear();
            IpAddresses.Clear();
            UserAgents.Clear();
        }
    }
}

