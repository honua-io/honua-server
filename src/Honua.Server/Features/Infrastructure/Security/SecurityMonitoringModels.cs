/// <summary>
/// IP address behavioral profile for threat detection.
/// </summary>
public class IpBehaviorProfile
{
    public string IpAddress { get; set; } = string.Empty;
    public DateTime FirstSeen { get; set; }
    public DateTime LastSeen { get; set; }
    public List<IpActivity> ActivityHistory { get; set; } = new();
    public Dictionary<AuditEventType, int> EventTypeCounts { get; set; } = new();
    public Dictionary<string, int> UserCounts { get; set; } = new();
    public Dictionary<string, int> ResourceCounts { get; set; } = new();
    public int FailedAuthenticationCount { get; set; }
    public int SuccessfulAuthenticationCount { get; set; }
    public bool IsSuspicious { get; set; }
    public List<string> SuspiciousFlags { get; set; } = new();

    public void UpdateActivity(AuditEvent auditEvent)
    {
        LastSeen = auditEvent.Timestamp;

        ActivityHistory.Add(new IpActivity
        {
            Timestamp = auditEvent.Timestamp,
            EventType = auditEvent.EventType,
            UserId = auditEvent.UserId,
            Resource = auditEvent.Resource,
            Action = auditEvent.Action,
            UserAgent = auditEvent.UserAgent
        });

        // Maintain sliding window
        var cutoff = DateTime.UtcNow.AddDays(-7);
        ActivityHistory.RemoveAll(a => a.Timestamp < cutoff);

        // Update counts
        EventTypeCounts[auditEvent.EventType] = EventTypeCounts.GetValueOrDefault(auditEvent.EventType, 0) + 1;

        if (!string.IsNullOrEmpty(auditEvent.UserId))
        {
            UserCounts[auditEvent.UserId] = UserCounts.GetValueOrDefault(auditEvent.UserId, 0) + 1;
        }

        if (!string.IsNullOrEmpty(auditEvent.Resource))
        {
            ResourceCounts[auditEvent.Resource] = ResourceCounts.GetValueOrDefault(auditEvent.Resource, 0) + 1;
        }

        // Track authentication attempts
        if (auditEvent.EventType == AuditEventType.AuthenticationFailure)
        {
            FailedAuthenticationCount++;
        }
        else if (auditEvent.EventType == AuditEventType.AuthenticationSuccess)
        {
            SuccessfulAuthenticationCount++;
        }

        // Update suspicious flags
        UpdateSuspiciousFlags();
    }

    private void UpdateSuspiciousFlags()
    {
        SuspiciousFlags.Clear();

        // High failure rate
        var totalAuth = FailedAuthenticationCount + SuccessfulAuthenticationCount;
        if (totalAuth > 10 && (double)FailedAuthenticationCount / totalAuth > 0.8)
        {
            SuspiciousFlags.Add("HIGH_FAILURE_RATE");
        }

        // Multiple users from same IP
        if (UserCounts.Count > 5)
        {
            SuspiciousFlags.Add("MULTIPLE_USERS");
        }

        // High activity volume
        var recentActivity = ActivityHistory.Count(a => a.Timestamp > DateTime.UtcNow.AddHours(-1));
        if (recentActivity > 100)
        {
            SuspiciousFlags.Add("HIGH_ACTIVITY_VOLUME");
        }

        // Diverse resource access
        if (ResourceCounts.Count > 20)
        {
            SuspiciousFlags.Add("DIVERSE_RESOURCE_ACCESS");
        }

        IsSuspicious = SuspiciousFlags.Count > 0;
    }

    public void CleanupOldData(DateTime cutoff)
    {
        ActivityHistory.RemoveAll(a => a.Timestamp < cutoff);

        if (FirstSeen < cutoff.AddMonths(-3))
        {
            EventTypeCounts.Clear();
            UserCounts.Clear();
            ResourceCounts.Clear();
            FailedAuthenticationCount = 0;
            SuccessfulAuthenticationCount = 0;
            SuspiciousFlags.Clear();
            IsSuspicious = false;
        }
    }
}

