  append_cert_result "$proto" "CERT-GEOM-02" "$LAST_STATUS" "$LAST_DURATION_MS" "" "" ""

  # CERT-ERRH-01: Invalid endpoint returns structured error
  request_json_4xx \
    "fs-error-invalid" \
    "${fs_base}/99999?f=json" \
    '.error != null' || failed=1
