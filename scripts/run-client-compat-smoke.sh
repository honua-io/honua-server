  request_json \
    "ogc-geometry-type" \
    "${ogc_base}/collections/${LAYER_ID}/items?limit=1" "200" \
    '.features[0].geometry.type == "Point"' || failed=1
  append_cert_result "$proto" "CERT-SCHM-02" "$LAST_STATUS" "$LAST_DURATION_MS" "" "" ""

  # CERT-QFLT-01: Attribute filter via CQL2 (verify returned features have matching status)
  request_json \
    "ogc-attribute-filter" \
    "${ogc_base}/collections/${LAYER_ID}/items?filter=status%20%3D%20%27active%27&limit=3" "200" \
    '(.features | length) > 0 and (.features | length) <= 3 and ([.features[].properties.status] | all(. == "active"))' || failed=1
  local qflt01_count=""
  if [[ -f "$LAST_BODY_PATH" ]]; then
    qflt01_count=$(jq -r '.features | length' "$LAST_BODY_PATH" 2>/dev/null || echo "")
  fi
  append_cert_result "$proto" "CERT-QFLT-01" "$LAST_STATUS" "$LAST_DURATION_MS" "$qflt01_count" "" ""

  # CERT-QFLT-02: Spatial bbox filter (bbox contains exactly alpha/beta/gamma)
  request_json \
    "ogc-bbox-query" \
    "${ogc_base}/collections/${LAYER_ID}/items?bbox=-122.50%2C37.70%2C-122.45%2C37.74&limit=10" "200" \
    '(.features | length) == 3 and ([.features[].geometry.coordinates | (.[0] >= -122.50 and .[0] <= -122.45 and .[1] >= 37.70 and .[1] <= 37.74)] | all)' || failed=1
  local qflt02_count=""
  if [[ -f "$LAST_BODY_PATH" ]]; then
    qflt02_count=$(jq -r '.features | length' "$LAST_BODY_PATH" 2>/dev/null || echo "")
  fi
  append_cert_result "$proto" "CERT-QFLT-02" "$LAST_STATUS" "$LAST_DURATION_MS" "$qflt02_count" "" ""

  # CERT-PAGE-01: First page
  request_json \
    "ogc-items-first-page" \
    "${ogc_base}/collections/${LAYER_ID}/items?limit=3" "200" \
    '(.features | length) == 3' || failed=1
  local page01_count=""
  local page01_fids=""
  if [[ -f "$LAST_BODY_PATH" ]]; then
    page01_count=$(jq -r '.features | length' "$LAST_BODY_PATH" 2>/dev/null || echo "")
    page01_fids=$(jq -c '[.features[].id]' "$LAST_BODY_PATH" 2>/dev/null || echo "")
  fi
  append_cert_result "$proto" "CERT-PAGE-01" "$LAST_STATUS" "$LAST_DURATION_MS" "$page01_count" "" ""

  # CERT-PAGE-02: Second page offset (non-overlapping features)
  local ogc_page02_jq='(.features | length) == 3'
  if [[ -n "$page01_fids" && "$page01_fids" != "null" ]]; then
    ogc_page02_jq="((.features | length) == 3) and (([.features[].id] - ${page01_fids}) | length) == (.features | length)"
  fi
  request_json \
    "ogc-page-second" \
    "${ogc_base}/collections/${LAYER_ID}/items?limit=3&offset=3" "200" \
    "$ogc_page02_jq" || failed=1
  append_cert_result "$proto" "CERT-PAGE-02" "$LAST_STATUS" "$LAST_DURATION_MS" "" "" ""

  # CERT-GEOM-01: Coordinate fidelity (GeoJSON: coordinates[0]=x, coordinates[1]=y)
  request_json \
    "ogc-geom-coords" \
    "${ogc_base}/collections/${LAYER_ID}/items?filter=name%20%3D%20%27alpha%27&limit=1" "200" \
    '.features[0].geometry.coordinates | (((.[0]) - (-122.49)) | fabs) < 0.000001 and (((.[1]) - 37.71) | fabs) < 0.000001' || failed=1
  local geom01_delta=""
  if [[ "$LAST_STATUS" == "pass" && -f "$LAST_BODY_PATH" ]]; then
    geom01_delta=$(jq -r '.features[0].geometry.coordinates | [((.[0] - (-122.49)) | fabs), ((.[1] - 37.71) | fabs)] | max' "$LAST_BODY_PATH" 2>/dev/null || echo "")
  fi
  append_cert_result "$proto" "CERT-GEOM-01" "$LAST_STATUS" "$LAST_DURATION_MS" "" "$geom01_delta" ""

  # CERT-GEOM-02: Output CRS matches requested CRS (explicit EPSG:4326, north/east axis order)
  # EPSG:4326 swaps axes to lat/lon: alpha at (-122.49, 37.71) becomes [37.71, -122.49]
  request_json \
    "ogc-geom-crs" \
    "${ogc_base}/collections/${LAYER_ID}/items?filter=name%20%3D%20%27alpha%27&limit=1&crs=http%3A%2F%2Fwww.opengis.net%2Fdef%2Fcrs%2FEPSG%2F0%2F4326" "200" \
    '.features[0].geometry.coordinates | (((.[0]) - 37.71) | fabs) < 0.000001 and (((.[1]) - (-122.49)) | fabs) < 0.000001' || failed=1
  local geom02_status="$LAST_STATUS"
  if [[ "$geom02_status" == "pass" && -f "$LAST_HEADERS_PATH" ]]; then
    if ! grep -qi 'content-crs:.*EPSG/0/4326' "$LAST_HEADERS_PATH"; then
      geom02_status="fail"
      # Propagate header failure to lane check result so lane/overall summaries stay consistent
      awk -F'\t' -v OFS='\t' '$1 == "ogc-geom-crs" { $2 = "fail"; $5 = "Content-Crs header missing or does not match EPSG:4326" }1' \
        "$CURRENT_RESULTS_FILE" > "${CURRENT_RESULTS_FILE}.tmp" && mv "${CURRENT_RESULTS_FILE}.tmp" "$CURRENT_RESULTS_FILE"
      failed=1
    fi
  fi
  append_cert_result "$proto" "CERT-GEOM-02" "$geom02_status" "$LAST_DURATION_MS" "" "" ""

  # CERT-ERRH-01: Invalid collection
  request_json_4xx \
    "ogc-error-invalid" \
    "${ogc_base}/collections/nonexistent_99999" \
    'type == "object" and length > 0' || failed=1
  append_cert_result "$proto" "CERT-ERRH-01" "$LAST_STATUS" "$LAST_DURATION_MS" "" "" ""

  # CERT-ERRH-02: Malformed filter
  request_json_4xx \
    "ogc-error-malformed" \
    "${ogc_base}/collections/${LAYER_ID}/items?filter=INVALID%21%21%21" \
    'type == "object" and length > 0' || failed=1
  append_cert_result "$proto" "CERT-ERRH-02" "$LAST_STATUS" "$LAST_DURATION_MS" "" "" ""

  # CERT-RNDR-01, RNDR-02 (skip)
  record_skip_with_lane "ogc-rndr-render" "$proto" "CERT-RNDR-01" "Visual rendering requires manual client"
  record_skip_with_lane "ogc-rndr-refresh" "$proto" "CERT-RNDR-02" "Data refresh requires manual client"

