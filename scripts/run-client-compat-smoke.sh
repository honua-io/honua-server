run_full_featureserver() {
  local failed=0
  local proto="featureserver"
  local fs_base="${BASE_URL}/rest/services/${SERVICE_ID}/FeatureServer"

  # CERT-CONN-01: HTTP connection (GET; server routes do not support HEAD)
  request_json "fs-conn-check" "${fs_base}?f=json" "200" "true" || failed=1
  append_cert_result "$proto" "CERT-CONN-01" "$LAST_STATUS" "$LAST_DURATION_MS" "" "" ""

  # CERT-CONN-02, AUTH-01, AUTH-02 (skip)
  record_skip_with_lane "fs-conn-tls" "$proto" "CERT-CONN-02" "HTTP-only CI environment; TLS not available"
  record_skip_with_lane "fs-auth-unauth" "$proto" "CERT-AUTH-01" "No auth configured in CI seed"
  record_skip_with_lane "fs-auth-valid" "$proto" "CERT-AUTH-02" "No auth configured in CI seed"

  # CERT-DISC-01: List services
  request_json \
    "featureserver-service-metadata" \
    "${fs_base}?f=json" "200" \
    "(.layers | length) > 0 and (.layers[0].id == ${LAYER_ID})" || failed=1
  local disc01_count=""
  if [[ -f "$LAST_BODY_PATH" ]]; then
    disc01_count=$(jq -r '.layers | length' "$LAST_BODY_PATH" 2>/dev/null || echo "")
  fi
  append_cert_result "$proto" "CERT-DISC-01" "$LAST_STATUS" "$LAST_DURATION_MS" "$disc01_count" "" ""

  # CERT-DISC-02: Layer metadata
  request_json \
    "featureserver-layer-metadata" \
    "${fs_base}/${LAYER_ID}?f=json" "200" \
    ".id == ${LAYER_ID} and (.fields | length) > 0 and .geometryType == \"esriGeometryPoint\"" || failed=1
  append_cert_result "$proto" "CERT-DISC-02" "$LAST_STATUS" "$LAST_DURATION_MS" "" "" ""

  # CERT-SCHM-01: Typed fields array
  request_json \
    "fs-schema-fields" \
    "${fs_base}/${LAYER_ID}?f=json" "200" \
    '(.fields | length) > 0 and .fields[0].type != null' || failed=1
  append_cert_result "$proto" "CERT-SCHM-01" "$LAST_STATUS" "$LAST_DURATION_MS" "" "" ""

  # CERT-SCHM-02: Geometry type
  request_json \
    "fs-geometry-type" \
    "${fs_base}/${LAYER_ID}?f=json" "200" \
    '.geometryType == "esriGeometryPoint"' || failed=1
  append_cert_result "$proto" "CERT-SCHM-02" "$LAST_STATUS" "$LAST_DURATION_MS" "" "" ""

  # CERT-QFLT-01: Attribute filter (verify returned features have matching status)
  request_json \
    "featureserver-query-active-subset" \
    "${fs_base}/${LAYER_ID}/query?where=status%20%3D%20%27active%27&resultRecordCount=3&returnGeometry=true&f=json" \
    "200" \
    '(.features | length) == 3 and ([.features[].attributes.status] | all(. == "active"))' || failed=1
  local qflt01_count=""
  if [[ -f "$LAST_BODY_PATH" ]]; then
    qflt01_count=$(jq -r '.features | length' "$LAST_BODY_PATH" 2>/dev/null || echo "")
  fi
  append_cert_result "$proto" "CERT-QFLT-01" "$LAST_STATUS" "$LAST_DURATION_MS" "$qflt01_count" "" ""

  # CERT-QFLT-02: Spatial bbox filter (bbox contains exactly alpha/beta/gamma)
  request_json \
    "fs-bbox-query" \
    "${fs_base}/${LAYER_ID}/query?geometry=-122.50%2C37.70%2C-122.45%2C37.74&geometryType=esriGeometryEnvelope&inSR=4326&spatialRel=esriSpatialRelIntersects&returnGeometry=true&f=json" \
    "200" \
    '(.features | length) == 3 and ([.features[].geometry | (.x >= -122.50 and .x <= -122.45 and .y >= 37.70 and .y <= 37.74)] | all)' || failed=1
  local qflt02_count=""
