generate_cert_envelope() {
  local client_lane="$1" protocol="$2"
  local cert_results_file="$CERT_DIR/cert-results-${protocol}.tsv"
  local cert_json="$CERT_DIR/${TIMESTAMP}-${client_lane}-${protocol}.cert.json"
  local client_version
  client_version="curl/$(curl --version 2>/dev/null | head -1 | awk '{print $2}')"

  if [[ ! -f "$cert_results_file" ]]; then
    echo "Warning: no cert results for ${protocol}, skipping envelope" >&2
    return 0
  fi

  jq -Rn \
    --arg schema_version "1.0" \
    --arg run_id "$TIMESTAMP" \
    --arg run_date "$GENERATED_AT" \
    --arg server_version "$SERVER_VERSION" \
    --arg client_lane "$client_lane" \
    --arg client_version "$client_version" \
    --arg protocol "$protocol" \
    --arg environment "ci" \
    '
      [inputs | select(length > 0) | split("\t")] as $rows
      | {
          schema_version: $schema_version,
          run_id: $run_id,
          run_date: $run_date,
          server_version: $server_version,
          client_lane: $client_lane,
          client_version: $client_version,
          protocol: $protocol,
          environment: $environment,
          results: [
            $rows[]
            | {
                test_case_id: .[0],
                status: .[1],
                duration_ms: (if (.[2] // "") == "" then null else (.[2] | tonumber) end),
                measured_count: (if (.[3] // "") == "" then null else (.[3] | tonumber) end),
                measured_delta: (if (.[4] // "") == "" then null else (.[4] | tonumber) end),
                notes: (if (.[5] // "") == "" then "" else .[5] end),
                evidence_ref: (if (.[6] // "") == "" then "" else .[6] end)
              }
          ],
          summary: {
            total: ($rows | length),
            passed: ($rows | map(select(.[1] == "pass")) | length),
            failed: ($rows | map(select(.[1] == "fail")) | length),
            skipped: ($rows | map(select(.[1] == "skip")) | length),
            not_applicable: ($rows | map(select(.[1] == "not-applicable")) | length)
          },
          cite_results: null,
          extensions: []
        }
    ' < "$cert_results_file" > "$cert_json"

  echo "Generated: ${cert_json#$ROOT_DIR/}"
}

