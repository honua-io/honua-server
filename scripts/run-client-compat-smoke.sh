}

CURRENT_LANE=""
CURRENT_RESULTS_FILE=""

lane_dir() {
  printf '%s\n' "$LANES_DIR/$1"
}

init_lane() {
  CURRENT_LANE="$1"
  local lane_path
  lane_path="$(lane_dir "$CURRENT_LANE")"
  mkdir -p "$lane_path/transcripts"
  CURRENT_RESULTS_FILE="$lane_path/checks.tsv"
  : > "$CURRENT_RESULTS_FILE"
}

append_result() {
  local check_id="$1"
  local status="$2"
  local http_status="$3"
  local transcript_rel="$4"
  local note="$5"

  note="${note//$'\n'/ }"
  printf '%s\t%s\t%s\t%s\t%s\n' "$check_id" "$status" "$http_status" "$transcript_rel" "$note" >> "$CURRENT_RESULTS_FILE"
}

write_transcript() {
  local transcript_file="$1"
  local method="$2"
  local url="$3"
  local accept="$4"
  local http_status="$5"
  local note="$6"
  local headers_file="$7"
  local body_file="$8"

  {
    echo "# Request"
    echo "${method} ${url}"
    echo "Accept: ${accept}"
    echo
    echo "# Response"
    echo "HTTP ${http_status}"
    if [[ -n "$note" ]]; then
      echo "Note: ${note}"
    fi
    echo
    echo "## Headers"
    cat "$headers_file"
    echo
    echo "## Body"
    cat "$body_file"
  } > "$transcript_file"
}

request_json() {
  local check_id="$1"
  local url="$2"
  local expected_status="$3"
  local jq_expr="$4"
  local accept="${5:-application/json}"

  local lane_path headers_file body_file transcript_file transcript_rel http_status curl_exit status note
  lane_path="$(lane_dir "$CURRENT_LANE")"
  headers_file="$(mktemp)"
  body_file="$(mktemp)"
  transcript_file="$lane_path/transcripts/${check_id}.txt"
  transcript_rel="${transcript_file#$ARTIFACT_ROOT/}"
  http_status="0"
  curl_exit=0
  status="pass"
  note=""
  LAST_DURATION_MS="0"

  local curl_output time_total
  curl_output="$(curl -sS -o "$body_file" -D "$headers_file" -H "Accept: ${accept}" -w '%{http_code}\t%{time_total}' "$url")" || curl_exit=$?
  http_status="${curl_output%%$'\t'*}"
  time_total="${curl_output#*$'\t'}"
  LAST_DURATION_MS="$(awk "BEGIN {printf \"%.0f\", ${time_total:-0} * 1000}")"

  if [[ $curl_exit -ne 0 ]]; then
    status="fail"
    note="curl exited with code ${curl_exit}"
  elif [[ "$http_status" != "$expected_status" ]]; then
    status="fail"
    note="expected HTTP ${expected_status}, got ${http_status}"
  elif ! jq -e "$jq_expr" "$body_file" >/dev/null 2>&1; then
    status="fail"
    note="response failed jq assertion: ${jq_expr}"
  fi

  write_transcript "$transcript_file" "GET" "$url" "$accept" "$http_status" "$note" "$headers_file" "$body_file"
  append_result "$check_id" "$status" "$http_status" "$transcript_rel" "$note"

  rm -f "$LAST_BODY_PATH" 2>/dev/null || true
  LAST_BODY_PATH="$body_file"
  rm -f "$LAST_HEADERS_PATH" 2>/dev/null || true
  LAST_HEADERS_PATH="$headers_file"
  LAST_STATUS="$status"

  [[ "$status" == "pass" ]]
}

