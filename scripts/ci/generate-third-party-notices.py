#!/usr/bin/env python3
"""Regenerate the .NET package table in THIRD-PARTY-NOTICES.md.

Reads every <PackageVersion> in Directory.Packages.props (root and the custom-code
harness), classifies each package as shipping (referenced by a project under src/)
or test-only (referenced only under tests/ or scripts/), and resolves the license
expression from nuget.org registration metadata. Only shipping packages are
listed; test-only packages are not distributed.

The table lives between the markers below; every other section of the notices
file is hand-maintained (native libraries, base images) and is left untouched.

    python3 scripts/ci/generate-third-party-notices.py          # rewrite
    python3 scripts/ci/generate-third-party-notices.py --check  # fail if stale
"""
from __future__ import annotations

import argparse
import concurrent.futures
import glob
import gzip
import json
import re
import sys
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
NOTICES = REPO_ROOT / "THIRD-PARTY-NOTICES.md"
PROPS = [
    REPO_ROOT / "Directory.Packages.props",
    REPO_ROOT / "docker/worker-customcode-dotnet/harness/Directory.Packages.props",
]
START = "<!-- nuget-table:start (generated by scripts/ci/generate-third-party-notices.py) -->"
END = "<!-- nuget-table:end -->"

# Packages that publish a license file instead of an SPDX expression.
LICENSE_OVERRIDES = {
    "Amazon.Lambda.Serialization.SystemTextJson": "Apache-2.0",
    "Apache.Arrow": "Apache-2.0",
    "FlatGeobuf": "BSD-2-Clause",
    "Oracle.ManagedDataAccess.Core": "Oracle Free Use Terms and Conditions (FUTC)",
}


def pinned_packages() -> dict[str, str]:
    packages: dict[str, str] = {}
    for props in PROPS:
        if not props.exists():
            continue
        for match in re.finditer(r'<PackageVersion\s+Include="([^"]+)"\s+Version="([^"]+)"', props.read_text("utf-8")):
            packages.setdefault(match.group(1), match.group(2))
    return packages


def shipping_packages() -> set[str]:
    shipping: set[str] = set()
    for csproj in glob.glob(str(REPO_ROOT / "**/*.csproj"), recursive=True):
        rel = Path(csproj).relative_to(REPO_ROOT).as_posix()
        if rel.startswith("src/") or "/harness/src/" in rel:
            text = Path(csproj).read_text("utf-8", errors="ignore")
            shipping.update(re.findall(r'<PackageReference\s+Include="([^"]+)"', text))
    return shipping


def _get_json(url: str) -> dict:
    request = urllib.request.Request(url, headers={"User-Agent": "honua-third-party-notices", "Accept-Encoding": "gzip"})
    with urllib.request.urlopen(request, timeout=60) as response:
        body = response.read()
    if body[:2] == b"\x1f\x8b":
        body = gzip.decompress(body)
    return json.loads(body)


def resolve(package: str, version: str) -> dict[str, str]:
    registration = _get_json(f"https://api.nuget.org/v3/registration5-gz-semver2/{package.lower()}/{version.lower()}.json")
    entry = registration.get("catalogEntry")
    if isinstance(entry, str):
        entry = _get_json(entry)
    license_expression = entry.get("licenseExpression") or LICENSE_OVERRIDES.get(package, "see package")
    project = entry.get("projectUrl") or entry.get("licenseUrl") or ""
    return {"package": package, "version": version, "license": license_expression, "project": project}


def render_table(rows: list[dict[str, str]]) -> str:
    lines = ["| Package | Version | License | Project |", "|---|---|---|---|"]
    for row in sorted(rows, key=lambda r: r["package"].lower()):
        lines.append(f"| {row['package']} | {row['version']} | {row['license']} | {row['project']} |")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when the table in THIRD-PARTY-NOTICES.md is stale")
    args = parser.parse_args()

    pinned = pinned_packages()
    shipping = shipping_packages()
    targets = [(name, version) for name, version in pinned.items() if name in shipping]
    with concurrent.futures.ThreadPoolExecutor(max_workers=12) as pool:
        rows = list(pool.map(lambda item: resolve(*item), targets))

    current = NOTICES.read_text("utf-8")
    if START not in current or END not in current:
        print(f"{NOTICES.relative_to(REPO_ROOT)}: generated-table markers are missing", file=sys.stderr)
        return 2
    head, rest = current.split(START, 1)
    _, tail = rest.split(END, 1)
    updated = f"{head}{START}\n{render_table(rows)}\n{END}{tail}"

    if args.check:
        if updated != current:
            print("THIRD-PARTY-NOTICES.md is stale; run scripts/ci/generate-third-party-notices.py", file=sys.stderr)
            return 1
        print(f"THIRD-PARTY-NOTICES.md is current ({len(rows)} shipping packages).")
        return 0
    NOTICES.write_text(updated, "utf-8")
    print(f"Wrote {len(rows)} shipping packages to {NOTICES.relative_to(REPO_ROOT)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
