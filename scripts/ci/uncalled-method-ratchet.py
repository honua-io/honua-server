#!/usr/bin/env python3
"""Ratchet for methods under src/ that nothing calls.

A method is uncalled when its name occurs exactly once across the repository's
code and configuration text (C#, Razor, JSON, YAML, XML, MSBuild, scripts) after
C# comments are removed: that one occurrence is its declaration. String literals
stay, so a name used through reflection or configuration still counts as used.
Overrides, framework entry points and non-private members of types that derive
from or implement a type not declared under src/ (framework interfaces, SignalR
hubs, gRPC interceptors) are skipped, and the CLI template sources
under src/Honua.Geoprocessing/Cli/Templates are content, not product code.
Prints one "path::Name" entry per line. The architecture test commits the output
as a baseline and refuses new entries and stale ones.

Usage:
    python3 scripts/ci/uncalled-method-ratchet.py
    python3 scripts/ci/uncalled-method-ratchet.py --self-test
    python3 scripts/ci/uncalled-method-ratchet.py --write tests/dotnet/Honua.Architecture.Tests/uncalled-method-baseline.txt
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

TEXT_SUFFIXES = (
    ".cs", ".razor", ".cshtml", ".json", ".xml", ".yaml", ".yml", ".props", ".targets",
    ".csproj", ".ps1", ".sh", ".py", ".ts", ".js",
)
EXCLUDED_PREFIXES = ("docs/", "src/Honua.Geoprocessing/Cli/Templates/")
FRAMEWORK_NAMES = {"Main", "Dispose", "DisposeAsync", "ToString", "Equals", "GetHashCode", "Configure", "ConfigureServices"}
TYPE_HEADER = re.compile(r"\b(?:class|struct|record)\s+\w+(?:<[^>{]*>)?(?:\([^)]*\))?\s*:\s*([^{;]+?)\s*(?:where\b[^{]*)?\{")
DECLARED_TYPE = re.compile(r"\b(?:class|struct|record|interface|enum)\s+([A-Z]\w*)")
WORD = re.compile(r"\b[A-Za-z_]\w*\b")
DECLARATION = re.compile(
    r"^[ \t]*(?:\[[^\]\n]*\][ \t]*)*"
    r"(?P<modifiers>(?:(?:public|internal|private|protected|static|async|virtual|sealed|partial|new|unsafe|extern|override)\s+)+)"
    r"[\w<>\[\],.?() ]+?\s+(?P<name>[A-Z]\w*)\s*(?:<[^>()]*>)?\s*\(",
    re.M,
)

HEADER = """# Generated by scripts/ci/uncalled-method-ratchet.py. Do not add lines.
# Each line is a method under src/ whose name appears only at its declaration.
# Delete a line when the method is deleted or gains a caller.
"""


def tracked_files(root: Path) -> list[str]:
    result = subprocess.run(["git", "-C", str(root), "ls-files"], capture_output=True, text=True, check=True)
    return [line for line in result.stdout.splitlines() if line.endswith(TEXT_SUFFIXES) and not line.startswith(EXCLUDED_PREFIXES)]


def strip_comments(s: str) -> str:
    """Remove C# comments, leaving string and char literals (regular, verbatim, interpolated, raw) intact."""
    out, i, n = [], 0, len(s)
    while i < n:
        c = s[i]
        if s.startswith('//', i):
            j = s.find('\n', i); i = n if j == -1 else j; continue
        if s.startswith('/*', i):
            j = s.find('*/', i + 2); i = n if j == -1 else j + 2; out.append(' '); continue
        if c == "'":
            j = i + 1
            while j < n and s[j] != "'":
                j += 2 if s[j] == '\\' else 1
            out.append(s[i:j + 1]); i = j + 1; continue
        if c in '$@' or c == '"':
            k = i
            while k < n and s[k] in '$@': k += 1
            if k < n and s[k] == '"':
                prefix = s[i:k]
                if s.startswith('"""', k):
                    q = 3
                    while s.startswith('"', k + q): q += 1
                    end = s.find('"' * q, k + q); end = n if end == -1 else end + q
                elif '@' in prefix:
                    j = k + 1
                    while j < n:
                        if s[j] == '"':
                            if s.startswith('""', j): j += 2; continue
                            break
                        j += 1
                    end = j + 1
                else:
                    j = k + 1; depth = 0
                    while j < n:
                        ch = s[j]
                        if ch == '\\': j += 2; continue
                        if '$' in prefix:
                            if ch == '{' and not s.startswith('{{', j): depth += 1
                            elif ch == '}' and depth: depth -= 1
                        if ch == '"' and depth == 0: break
                        j += 1
                    end = j + 1
                out.append(s[i:end]); i = end; continue
        out.append(c); i += 1
    return ''.join(out)


def type_spans(text: str) -> list[tuple[int, int, list[str]]]:
    spans = []
    for header in TYPE_HEADER.finditer(text):
        open_index, depth, index = header.end() - 1, 0, header.end() - 1
        while index < len(text):
            if text[index] == "{":
                depth += 1
            elif text[index] == "}":
                depth -= 1
                if depth == 0:
                    break
            index += 1
        bases = [part.strip().split("<")[0].split(".")[-1].split("(")[0].strip()
                 for part in re.split(r",(?![^<]*>)", header.group(1))]
        spans.append((open_index, index, bases))
    return spans


def has_external_base(spans: list[tuple[int, int, list[str]]], position: int, declared: set[str]) -> bool:
    inner = None
    for start, end, bases in spans:
        if start < position < end and (inner is None or start > inner[0]):
            inner = (start, end, bases)
    return inner is not None and any(base and base not in declared for base in inner[2])


def scan(root: Path) -> list[str]:
    words: Counter[str] = Counter()
    sources: dict[str, str] = {}
    for relative in tracked_files(root):
        path = root / relative
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        if relative.endswith(".cs"):
            text = strip_comments(text)
            if relative.startswith("src/"):
                sources[relative] = text
        words.update(WORD.findall(text))

    declared = {name for text in sources.values() for name in DECLARED_TYPE.findall(text)}
    entries = set()
    for relative, text in sources.items():
        spans = None
        for match in DECLARATION.finditer(text):
            name = match.group("name")
            modifiers = match.group("modifiers").split()
            if name in FRAMEWORK_NAMES or "override" in modifiers or words[name] != 1:
                continue
            if "private" not in modifiers and any(m in modifiers for m in ("public", "protected", "internal")):
                spans = spans if spans is not None else type_spans(text)
                if has_external_base(spans, match.start(), declared):
                    continue
            entries.add(f"{relative}::{name}")
    return sorted(entries)


def self_test() -> int:
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        (root / "src").mkdir()
        (root / "src" / "Sample.cs").write_text(
            "public class Sample\n{\n"
            "    public void Used() { }\n"
            "    public void Unused() { }\n"
            "    // Commented() is only mentioned in a comment\n"
            "    public void Commented() { }\n"
            "    public void Reflected() { }\n"
            "    public override string ToString() => \"\";\n"
            "    private void Caller() { Used(); var name = \"Reflected\"; }\n"
            "    private void Masked() { var media = \"text/*\"; }\n"
            "    private void MaskedCaller() { Masked(); var closing = \"*/\"; }\n"
            "}\n"
            "public class Writer : System.Buffers.IBufferWriter<byte>\n{\n"
            "    public void Advance(int count) { }\n"
            "    private void Helper() { }\n"
            "}\n",
            encoding="utf-8",
        )
        subprocess.run(["git", "init", "-q", str(root)], check=True)
        subprocess.run(["git", "-C", str(root), "add", "."], check=True)
        actual = scan(root)
    expected = ["src/Sample.cs::Caller", "src/Sample.cs::Commented", "src/Sample.cs::Helper", "src/Sample.cs::MaskedCaller", "src/Sample.cs::Unused"]
    if actual != expected:
        print(f"self-test failed: expected {expected}, got {actual}", file=sys.stderr)
        return 1
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--write")
    parser.add_argument("--root", default=".")
    arguments = parser.parse_args()
    if arguments.self_test:
        return self_test()
    entries = scan(Path(arguments.root).resolve())
    if arguments.write:
        Path(arguments.write).write_text(HEADER + "".join(f"{entry}\n" for entry in entries), encoding="utf-8")
    else:
        print("\n".join(entries))
    return 0


if __name__ == "__main__":
    sys.exit(main())
