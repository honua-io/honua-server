"""Write requirements.lock for the Python custom-code worker from a pip resolution report.

The report comes from a dry-run install of requirements.in inside the worker's pinned
base image (see README.md, "Updating the Python packages"). For every package pip chose,
the lock records the exact version and the sha256 of each PyPI wheel that the image can
install on either Batch architecture (linux x86_64 and aarch64, CPython 3.12, glibc).
The image installs the lock with --require-hashes --no-deps --only-binary=:all:.

Usage: lock-requirements.py <pip-report.json> > requirements.lock
"""

from __future__ import annotations

import json
import sys
import urllib.request

from packaging.utils import canonicalize_name, parse_wheel_filename

PYTHON_TAGS = {"py3", "py2.py3", "cp312"}
ABI3_PYTHONS = {f"cp3{minor}" for minor in range(2, 13)}
ARCHITECTURES = ("x86_64", "aarch64")
HEADER = """\
# Generated by lock-requirements.py from requirements.in. Do not edit by hand.
# Exact versions with the sha256 of every linux x86_64 and aarch64 CPython 3.12 wheel;
# the image installs this file with --require-hashes --no-deps --only-binary=:all:.
# Regenerate: see README.md, "Updating the Python packages".
"""


def architectures(filename: str) -> set[str]:
    """The Batch architectures on which a wheel installs for CPython 3.12 on glibc Linux."""
    _, _, _, tags = parse_wheel_filename(filename)
    found = set()
    for tag in tags:
        python_ok = tag.interpreter in PYTHON_TAGS or (tag.abi == "abi3" and tag.interpreter in ABI3_PYTHONS)
        if not python_ok or tag.abi not in {"none", "abi3", "cp312"}:
            continue
        if tag.platform == "any":
            found.update(ARCHITECTURES)
        elif tag.platform.startswith("manylinux"):
            found.update(arch for arch in ARCHITECTURES if tag.platform.endswith(arch))
    return found


def wheel_hashes(name: str, version: str) -> tuple[list[str], set[str]]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as response:
        release = json.load(response)
    hashes, covered = set(), set()
    for file in release["urls"]:
        arches = architectures(file["filename"]) if file["packagetype"] == "bdist_wheel" else set()
        if arches:
            hashes.add(file["digests"]["sha256"])
            covered |= arches
    return sorted(hashes), covered


def lock_entry(item: dict) -> str:
    name, version = canonicalize_name(item["metadata"]["name"]), item["metadata"]["version"]
    hashes, covered = wheel_hashes(name, version)
    chosen = item["download_info"].get("archive_info", {}).get("hashes", {}).get("sha256")
    if chosen not in hashes:
        raise SystemExit(f"{name}=={version}: the resolved file is not among the installable wheels")
    for arch in sorted(set(ARCHITECTURES) - covered):
        print(f"warning: {name}=={version} has no {arch} wheel; a build for that architecture fails",
              file=sys.stderr)
    lines = [f"{name}=={version} \\"] + [f"    --hash=sha256:{digest} \\" for digest in hashes]
    lines[-1] = lines[-1].removesuffix(" \\")
    return "\n".join(lines)


def main(report_path: str) -> None:
    with open(report_path, encoding="utf-8") as handle:
        report = json.load(handle)
    entries = sorted(report["install"], key=lambda item: canonicalize_name(item["metadata"]["name"]))
    sys.stdout.write(HEADER + "\n".join(lock_entry(item) for item in entries) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
